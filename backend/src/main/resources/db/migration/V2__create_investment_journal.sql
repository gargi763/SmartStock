CREATE TABLE investment_journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    transaction_id BIGINT,
    title VARCHAR(120) NOT NULL,
    thesis VARCHAR(4000) NOT NULL,
    lessons_learned VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_journal_entry_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_journal_entry_transaction FOREIGN KEY (transaction_id) REFERENCES transactions (id)
);

CREATE TABLE investment_journal_tags (
    journal_entry_id BIGINT NOT NULL,
    tag VARCHAR(40) NOT NULL,
    CONSTRAINT pk_investment_journal_tags PRIMARY KEY (journal_entry_id, tag),
    CONSTRAINT fk_journal_tag_entry FOREIGN KEY (journal_entry_id)
        REFERENCES investment_journal_entries (id) ON DELETE CASCADE
);

CREATE INDEX idx_journal_entry_user_updated
    ON investment_journal_entries (user_id, updated_at);
