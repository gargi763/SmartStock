CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE stocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(10) NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    current_price NUMERIC(19, 4) NOT NULL,
    day_change NUMERIC(19, 4),
    day_change_percent NUMERIC(19, 4),
    market_source VARCHAR(255) NOT NULL,
    sector VARCHAR(255) NOT NULL,
    CONSTRAINT uk_stocks_symbol UNIQUE (symbol)
);

CREATE TABLE portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    cash_balance NUMERIC(19, 4) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_portfolios_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE holdings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL,
    stock_id BIGINT NOT NULL,
    quantity NUMERIC(19, 6) NOT NULL,
    average_cost NUMERIC(23, 8) NOT NULL,
    CONSTRAINT uk_holdings_portfolio_stock UNIQUE (portfolio_id, stock_id),
    CONSTRAINT fk_holdings_portfolio FOREIGN KEY (portfolio_id) REFERENCES portfolios (id),
    CONSTRAINT fk_holdings_stock FOREIGN KEY (stock_id) REFERENCES stocks (id)
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL,
    stock_id BIGINT NOT NULL,
    trade_type VARCHAR(255) NOT NULL,
    quantity NUMERIC(19, 6) NOT NULL,
    unit_price NUMERIC(19, 4) NOT NULL,
    total_amount NUMERIC(19, 4) NOT NULL,
    realized_profit_loss NUMERIC(19, 4) NOT NULL,
    status VARCHAR(255) NOT NULL,
    executed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_transactions_portfolio FOREIGN KEY (portfolio_id) REFERENCES portfolios (id),
    CONSTRAINT fk_transactions_stock FOREIGN KEY (stock_id) REFERENCES stocks (id)
);

CREATE TABLE watchlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    stock_id BIGINT NOT NULL,
    CONSTRAINT uk_watchlist_user_stock UNIQUE (user_id, stock_id),
    CONSTRAINT fk_watchlist_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_watchlist_stock FOREIGN KEY (stock_id) REFERENCES stocks (id)
);

CREATE INDEX idx_portfolios_user_id ON portfolios (user_id);
CREATE INDEX idx_holdings_stock_id ON holdings (stock_id);
CREATE INDEX idx_transactions_portfolio_executed ON transactions (portfolio_id, executed_at);
CREATE INDEX idx_transactions_stock_id ON transactions (stock_id);
CREATE INDEX idx_watchlist_stock_id ON watchlist_items (stock_id);
